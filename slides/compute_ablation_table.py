"""Full SCQF (formerly ANGEL) ablation table: forecast losses (panel A) and holdout early warning (panel B).

    .venv/bin/python slides/compute_ablation_table.py
    -> slides/data/ablation/scqf_ablation_table.csv, slides/tables/scqf_ablation.tex

Inputs (slides/data/ablation/, six seeds per variant, MLflow experiment 3603; run_manifest.csv lists the runs):
  forecast_summary_long.csv     mean / SD of every test loss per variant (comparison_nn_vs_arima/angel_ablation_study)
  forecast_block_bootstrap.csv  pooled % change vs the full model, 95% joint seed-and-time block bootstrap
                                (circular blocks of 168 forecast origins; rows with block_length == 168 are used)
  ablation_policy_grid.csv      holdout policy tallies of the raw exceedance probability (compute_ablation_ew.py)
  ablation_ranking.csv          hourly ROC AUC / AUPRC of the exceedance probability (compute_ablation_ew.py)
Early warning: rule S_t >= 0.1 for events, false alerts per month and V(0.1); WA-NBC = sum_r f(r) V(r) of the
decision rule S_t >= r over r in [0.01, 0.5] under the simple expected-loss prior and the LP prior
(slides/data/simple_cost_loss_weights.csv).
"""
from pathlib import Path

import numpy as np
import pandas as pd

S = Path(__file__).resolve().parent
D = S / "data/ablation"
TAB = S / "tables"
HPM = 730.5
ORDER = [("full", "Full SCQF"), ("crps_only", "CRPS loss only"), ("no_gpd", "No GPD tails"),
         ("gaussian", "Gaussian output"), ("no_sparsity", "No sparsity"), ("no_liq_shape", "No liquidity shape"),
         ("price_only", "Price only")]
GROUP = {"crps_only": "Loss and distributional head", "no_sparsity": "Input features"}
FC = [("CRPS", "CRPS"), ("twCRPS", "twCRPS"), ("twCRPS low", r"twCRPS$_{\mathrm{low}}$"),
      ("twCRPS high", r"twCRPS$_{\mathrm{high}}$"), ("QL 1%", r"QL$_{1\%}$"), ("QL 99%", r"QL$_{99\%}$")]
PRIORS = {"WA-NBC simple": "simple: expected loss", "WA-NBC LP": "LP prior"}


def early_warning():
    g = pd.read_csv(D / "ablation_policy_grid.csv")
    g["p"] = g.p.round(4)
    W = pd.read_csv(S / "data/simple_cost_loss_weights.csv", index_col=0)
    R = W.index.to_numpy().round(4)
    rows = []
    for (v, seed), t in g.groupby(["variant", "seed"]):
        t = t.set_index("p")
        p1 = t.loc[0.1]
        tr = t.loc[R]
        curve = ((tr.D - R * tr.A) / (tr.N * (1 - R))).to_numpy()
        rows.append(dict(variant=v, seed=seed, events=p1.D, eligible=p1.N, fa_pm=p1.F * HPM / p1.H,
                         V01=(p1.D - 0.1 * p1.A) / (p1.N * 0.9),
                         **{k: curve @ (W[c].to_numpy() / W[c].sum()) for k, c in PRIORS.items()}))
    ew = pd.DataFrame(rows).merge(pd.read_csv(D / "ablation_ranking.csv")[["variant", "seed", "auc", "auprc"]],
                                  on=["variant", "seed"])
    return ew


def main():
    TAB.mkdir(exist_ok=True)
    summ = pd.read_csv(D / "forecast_summary_long.csv").set_index(["variant", "metric"])
    bb = pd.read_csv(D / "forecast_block_bootstrap.csv")
    bb = bb[bb.block_length.eq(168)].set_index(["variant_b", "metric"])
    ew = early_warning()
    full = ew[ew.variant.eq("full")].set_index("seed")

    # ---------------------------------------------------------------- numbers (csv)
    out = []
    for v, name in ORDER:
        r = dict(variant=v, model=name)
        for m, _ in FC:
            if v == "full":
                r[m], r[f"{m} sd"] = summ.loc[(v, m), "mean"], summ.loc[(v, m), "sd"]
            else:
                b = bb.loc[(v, m)]
                r[f"{m} %"], r[f"{m} lo"], r[f"{m} hi"] = b.mean_pct, b.joint_pct_ci95_low, b.joint_pct_ci95_high
        e = ew[ew.variant.eq(v)].set_index("seed")
        for k in ["events", "fa_pm", "V01", *PRIORS, "auc", "auprc"]:
            r[k], r[f"{k} min"], r[f"{k} max"] = e[k].mean(), e[k].min(), e[k].max()
        for k in [*PRIORS, "V01", "auc"]:
            d = (e[k] - full[k].reindex(e.index)).dropna()
            r[f"{k} seeds below full"] = int((d < -1e-12).sum())
        r["seeds"], r["eligible events"] = len(e), int(e.eligible.iloc[0])
        out.append(r)
    t = pd.DataFrame(out)
    t.to_csv(D / "scqf_ablation_table.csv", index=False)
    ew.to_csv(D / "scqf_ablation_early_warning_seeds.csv", index=False)

    # ---------------------------------------------------------------- LaTeX
    sgn = lambda x, nd=1: (f"{x:+.{nd}f}").replace("-", "$-$").replace("+", "$+$")
    rng = lambda a, b, nd=1: rf"{{\scriptsize [{a:.{nd}f}, {b:.{nd}f}]}}".replace("-", "$-$")
    small = lambda s: rf"{{\scriptsize {s}}}"
    L = [r"% generated by slides/compute_ablation_table.py -- do not edit by hand",
         r"\begin{table}[pos=!htbp,align=\centering]",
         r"\caption{Ablations of the SCQF model, six seeds per variant. \textbf{Panel A}: test forecast losses. "
         r"The full-model row reports the mean loss with its standard deviation over seeds; ablation rows report the "
         r"pooled percentage change relative to the full model (positive is worse), with 95\% joint seed-and-time "
         r"block-bootstrap intervals (circular blocks of 168 forecast origins) below. Bold marks changes whose "
         r"interval excludes zero. \textbf{Panel B}: holdout early warning from the exceedance probability "
         r"$S_t=\max_{2\le h\le 24}\hat P(|d_{t+h}|\ge 15\,\text{bps})$ (5 eligible events, 2--24-hour timely "
         r"window, 12-hour alert reset). Events, false-alert episodes per month (FA/mo.) and $V_{0.1}$ "
         r"(Eq.~\eqref{eq:cost_loss_value}) are for the rule $S_t\ge 0.1$; WA-NBC is the weighted area under the "
         r"net-benefit curve of the rule $S_t\ge r$ for $r\in[0.01,0.5]$ under the expected-loss cost--loss prior "
         r"(simple) and the liquidity-provider prior (LP). Values are means over seeds, with the range over seeds "
         r"below; for WA-NBC, the number of seeds below the full model.}",
         r"\label{tab:scqf_ablation}",
         r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l rrrrrr@{}}",
         r"\toprule",
         r"\multicolumn{7}{@{}l}{\textbf{A. Forecast losses} ($\Delta$\%, lower is better)} \\",
         r"\midrule",
         "Ablation & " + " & ".join(h for _, h in FC) + r" \\", r"\midrule"]
    for _, r in t.iterrows():
        v = r.variant
        if v in GROUP:
            L += [r"\addlinespace[2pt]", rf"\multicolumn{{7}}{{@{{}}l}}{{\textit{{{GROUP[v]}}}}} \\"]
        if v == "full":
            L.append(rf"{r.model} & " + " & ".join(f"{r[m]:.4f}" for m, _ in FC) + r" \\")
            L.append(" & " + " & ".join(small(f"({r[f'{m} sd']:.4f})") for m, _ in FC) + r" \\")
            continue
        cells = []
        for m, _ in FC:
            s = sgn(r[f"{m} %"])
            sig = r[f"{m} lo"] > 0 or r[f"{m} hi"] < 0
            cells.append(rf"$\mathbf{{{s.replace('$', '')}}}$" if sig else s)
        L.append(rf"\quad {r.model} & " + " & ".join(cells) + r" \\")
        L.append(" & " + " & ".join(rng(r[f"{m} lo"], r[f"{m} hi"]) for m, _ in FC) + r" \\")
    L += [r"\midrule", r"\multicolumn{7}{@{}l}{\textbf{B. Early warning, holdout}} \\", r"\midrule",
          r"Ablation & Events $\uparrow$ & FA/mo.\ $\downarrow$ & $V_{0.1}$ $\uparrow$ & WA-NBC simple $\uparrow$ & "
          r"WA-NBC LP $\uparrow$ & AUC $\uparrow$ \\", r"\midrule"]
    for _, r in t.iterrows():
        v = r.variant
        if v in GROUP:
            L += [r"\addlinespace[2pt]", rf"\multicolumn{{7}}{{@{{}}l}}{{\textit{{{GROUP[v]}}}}} \\"]
        lab = r.model if v == "full" else rf"\quad {r.model}"
        L.append(rf"{lab} & {r.events:.1f} & {r.fa_pm:.2f} & {r.V01:.2f} & {r['WA-NBC simple']:.3f} & "
                 rf"{r['WA-NBC LP']:.3f} & {r.auc:.3f} \\")
        below = lambda k: "" if v == "full" else small(f"({r[f'{k} seeds below full']}/{r.seeds})")
        L.append(" & " + small(f"({r['events min']:.0f}--{r['events max']:.0f})") + " & "
                 + rng(r["fa_pm min"], r["fa_pm max"], 2) + " & " + rng(r["V01 min"], r["V01 max"], 2) + " & "
                 + below("WA-NBC simple") + " & " + below("WA-NBC LP") + " & " + rng(r["auc min"], r["auc max"], 3)
                 + r" \\")
    L += [r"\bottomrule", r"\end{tabular*}", r"\end{table}"]
    (TAB / "scqf_ablation.tex").write_text("\n".join(L) + "\n")
    pd.set_option("display.width", 250)
    print(t[["model", "events", "fa_pm", "V01", "WA-NBC simple", "WA-NBC simple seeds below full", "WA-NBC LP",
             "auc", "auprc"]].round(3).to_string(index=False))


if __name__ == "__main__":
    main()
